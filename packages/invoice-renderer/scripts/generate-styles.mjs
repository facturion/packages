// Embed the stylesheets as JS strings so the renderer has no filesystem
// dependency (works in the browser as well as Node), and lay out the document
// face. Run via `npm run generate`. Emits:
//   src/styles.js      styles/invoice.css as a string
//   src/fonts.js       the IBM Plex Sans @font-face rules, files inlined as
//                      data: URIs — for an HTML→PDF engine with no network
//   styles/fonts.css   the same rules pointing at fonts/ — for a browser host
//   fonts/             the woff2 files and their licence (OFL)
// The face comes from @fontsource/ibm-plex-sans (a devDependency, so the files
// and unicode ranges are pinned by the lockfile rather than copied by hand).

import { copyFileSync, mkdirSync, readFileSync, writeFileSync, realpathSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { argv } from "node:process";
import { fileURLToPath } from "node:url";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const STYLES_DIR = join(PKG, "styles");
const FONTS_DIR = join(PKG, "fonts");
export const OUT = join(PKG, "src", "styles.js");
const FONTS_OUT = join(PKG, "src", "fonts.js");
const FONTS_CSS_OUT = join(STYLES_DIR, "fonts.css");

const FONTSOURCE = dirname(
  createRequire(import.meta.url).resolve("@fontsource/ibm-plex-sans/package.json"),
);
// Every weight invoice.css asks for, in every subset fontsource ships: an
// invoice can name a party in any EU script, and the unicode ranges mean a
// browser fetches only the subsets a document uses.
const WEIGHTS = [400, 500, 600, 700];

const banner = (from) =>
  `// Generated by scripts/generate-styles.mjs from ${from}.\n` +
  "// Do not edit by hand.\n";

/** The `src/styles.js` source — the invoice stylesheet as an escaped JS string. */
export function buildStylesModule() {
  const css = readFileSync(join(STYLES_DIR, "invoice.css"), "utf8");
  return `${banner("styles/invoice.css")}\nexport const invoiceCss = ${JSON.stringify(css)};\n`;
}

/** The faces fontsource declares for those weights: one per subset × weight. */
export function fontFaces() {
  return WEIGHTS.flatMap((weight) => {
    const css = readFileSync(join(FONTSOURCE, `${weight}.css`), "utf8");
    return [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map(([, body]) => ({
      weight,
      file: body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1],
      range: body.match(/unicode-range:\s*([^;]+);/)?.[1].trim(),
    }));
  });
}

const faceCss = ({ weight, range }, src, display) =>
  "@font-face {\n" +
  "  font-family: 'IBM Plex Sans';\n" +
  "  font-style: normal;\n" +
  `  font-weight: ${weight};\n` +
  `  font-display: ${display};\n` +
  `  src: url(${src}) format('woff2');\n` +
  (range ? `  unicode-range: ${range};\n` : "") +
  "}\n";

/** `styles/fonts.css` — the faces for a browser host, files beside the package. */
export function buildFontsCss(faces = fontFaces()) {
  return (
    "/* @facturion/invoice-renderer — the document face, IBM Plex Sans (SIL OFL\n" +
    " * 1.1, see fonts/OFL.txt). Generated by scripts/generate-styles.mjs from\n" +
    " * @fontsource/ibm-plex-sans; do not edit by hand. Import it beside\n" +
    " * invoice.css so a preview draws the same letters as the PDF. */\n\n" +
    faces.map((f) => faceCss(f, `../fonts/${f.file}`, "swap")).join("\n")
  );
}

/** The `src/fonts.js` source — the faces with their files inlined. `block`: an
 *  engine printing the page must not draw a fallback first. */
export function buildFontsModule(faces = fontFaces()) {
  const css = faces
    .map((f) => {
      const b64 = readFileSync(join(FONTSOURCE, "files", f.file)).toString("base64");
      return faceCss(f, `data:font/woff2;base64,${b64}`, "block");
    })
    .join("");
  return `${banner("@fontsource/ibm-plex-sans")}\nexport const fontFacesCss = ${JSON.stringify(css)};\n`;
}

const invokedDirectly =
  argv[1] !== undefined && realpathSync(argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const faces = fontFaces();
  mkdirSync(FONTS_DIR, { recursive: true });
  for (const { file } of faces) copyFileSync(join(FONTSOURCE, "files", file), join(FONTS_DIR, file));
  copyFileSync(join(FONTSOURCE, "LICENSE"), join(FONTS_DIR, "OFL.txt"));
  writeFileSync(FONTS_CSS_OUT, buildFontsCss(faces));
  writeFileSync(FONTS_OUT, buildFontsModule(faces));
  writeFileSync(OUT, buildStylesModule());
  process.stdout.write("Generated src/styles.js, src/fonts.js, styles/fonts.css, fonts/\n");
}
