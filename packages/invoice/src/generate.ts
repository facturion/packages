/** Generate the committed artifacts from the canonical schema.
 *
 *  Inputs : data/invoice-schema.json  (the canonical EN 16931 simplified-invoice
 *           contract — the language-neutral source of truth; Python and other
 *           consumers read the same JSON file).
 *  Outputs: generated/schema.ts        — the schema as a runtime object, so the
 *           validators compile it without a filesystem read at import time.
 *           generated/invoice-types.ts — TypeScript types derived from the
 *           schema via json-schema-to-typescript, one per direction (below).
 *           generated/fields.ts        — the BT/BG code → field maps and their
 *           types, for `field` / `setField` (src/fields.ts).
 *
 *  One schema, two directions. `readOnly` marks what only a document states
 *  (BG-22 totals, the VAT breakdown's amounts: computed, ignored on input);
 *  `writeOnly` marks what only a caller supplies (the top-level prepaid,
 *  rounding and accounting-currency VAT amounts, which the document states
 *  under `totals`). So:
 *    InvoiceInput — what the schema accepts: without the readOnly fields.
 *    Invoice      — the EN 16931 document: without the writeOnly fields, and
 *                   with what EN 16931 makes mandatory in a document (totals,
 *                   the VAT breakdown, line net amounts) required. A draft
 *                   becomes one through `completeInvoice`; a parsed invoice is one.
 *  Each code then has one path per direction.
 *
 *  All outputs are committed; test/artifacts.test.ts asserts they match a
 *  fresh regeneration. Run via `npm run generate`. */

import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { argv } from "node:process";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SCHEMA_PATH = join(PKG, "data", "invoice-schema.json");
export const GEN_DIR = join(PKG, "generated");

const BANNER =
  "// Generated by @facturion/invoice generate.ts from data/invoice-schema.json.\n" +
  "// Do not edit by hand.\n";

type Schema = Record<string, any>;

export function readSchema(): Schema {
  return JSON.parse(readFileSync(SCHEMA_PATH, "utf8")) as Schema;
}

/** The `generated/schema.ts` source — the schema as a runtime object. */
export function schemaModule(schema: Schema): string {
  return `${BANNER}\nexport const invoiceSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};\n`;
}

/** What EN 16931 makes mandatory in a document beyond the input's required
 *  fields, by schema path ("" the root, "[]" a list's entries): BG-22 and
 *  BG-23 (1..n), BT-131 on every line, and in BG-22 the sums BT-106, BT-109,
 *  BT-112 and BT-115; in BG-23 BT-116 and BT-117. `completeInvoice` fills each. */
const DOCUMENT_REQUIRED: Record<string, string[]> = {
  "": ["totals", "vat_breakdown"],
  "/lines/[]": ["net_amount"],
  "/totals": ["line_net_total", "tax_exclusive_amount", "tax_inclusive_amount", "amount_due"],
  "/vat_breakdown/[]": ["taxable_amount", "tax_amount"],
};

/** The schema for one direction: without the fields only the other one has. */
export function variantSchema(schema: Schema, direction: "input" | "document"): Schema {
  const drop = direction === "input" ? "readOnly" : "writeOnly";
  const walk = (node: any, path: string): any => {
    if (Array.isArray(node)) return node.map((n) => walk(n, path));
    if (!node || typeof node !== "object") return node;
    const out: Schema = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "properties") {
        const props: Schema = {};
        for (const [name, sub] of Object.entries(v as Schema)) {
          if (!(sub as Schema)[drop]) props[name] = walk(sub, `${path}/${name}`);
        }
        out.properties = props;
      } else if (k === "items") out.items = walk(v, `${path}/[]`);
      else if (k === "$defs") out.$defs = walk(v, "#defs");
      else out[k] = walk(v, path);
    }
    if (out.properties) {
      const extra = direction === "document" ? DOCUMENT_REQUIRED[path] ?? [] : [];
      const required = [...new Set([...(out.required ?? []), ...extra])].filter((r) => r in out.properties);
      if (required.length) out.required = required;
      else delete out.required;
    }
    return out;
  };
  const v = walk(schema, "");
  v.title = direction === "input" ? "InvoiceInput" : "Invoice";
  v.description =
    direction === "input"
      ? `${schema.description} This is the input: what the schema accepts, without the fields only a document states.`
      : "An EN 16931 invoice as a document: everything the input carries except the caller-only fields, with BG-22 totals, the VAT breakdown and line net amounts stated. `completeInvoice` turns an input into one.";
  return v;
}

async function compileType(schema: Schema): Promise<string> {
  const ts = await compile(schema as Parameters<typeof compile>[0], schema.title, {
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: true,
  });
  return ts.trim();
}

/** The `generated/invoice-types.ts` source — both directions' types. */
export async function typesModule(schema: Schema): Promise<string> {
  const input = await compileType(variantSchema(schema, "input"));
  const document = await compileType(variantSchema(schema, "document"));
  return `${BANNER}\n${input}\n\n${document}\n`;
}

// ── Field maps ───────────────────────────────────────────────────────────

const CODE = /^(B[TG]-\d+(?:-\d+)?)\s*\|/;

export interface FieldEntry {
  code: string;
  /** JSON Pointer pattern (`~*`: every entry of a list). A list's code names
   *  its entries: `BG-25` is `/lines/~*`. */
  pattern: string;
  /** Inside a list, so it has one value per entry. */
  many: boolean;
  /** The nearest list code whose entries contain it, and its pattern relative
   *  to such an entry. */
  group?: string;
  rel?: string;
}

/** Every code in `schema` (one direction) with its place. Throws when a code
 *  has two places: then a lookup by code would have to guess. */
export function fieldEntries(schema: Schema): FieldEntry[] {
  const out = new Map<string, FieldEntry>();
  const dupes: string[] = [];
  const deref = (n: Schema): Schema => {
    const ref = n?.$ref;
    if (typeof ref !== "string" || !ref.startsWith("#/$defs/")) return n;
    const { $ref: _, ...rest } = n;
    return { ...schema.$defs[ref.slice(8)], ...rest };
  };
  // `groups`: the enclosing list codes, innermost last, with the token index
  // where each one's entries begin.
  const walk = (node: Schema, toks: string[], groups: { code: string; at: number }[]) => {
    node = deref(node);
    if (!node || typeof node !== "object") return;
    const code = CODE.exec(node.description ?? "")?.[1];
    const isList = node.type === "array" || node.items;
    const here = isList ? [...toks, "~*"] : toks;
    if (code) {
      const g = groups.at(-1);
      const entry: FieldEntry = {
        code,
        pattern: `/${here.join("/")}`,
        many: here.includes("~*"),
        ...(g ? { group: g.code, rel: here.slice(g.at).join("/") } : {}),
      };
      if (out.has(code)) dupes.push(`${code}: ${out.get(code)!.pattern} and ${entry.pattern}`);
      else out.set(code, entry);
    }
    for (const comb of ["allOf", "anyOf", "oneOf"]) for (const sub of node[comb] ?? []) walk(sub, toks, groups);
    for (const [name, sub] of Object.entries<Schema>(node.properties ?? {})) walk(sub, [...toks, name], groups);
    if (node.items) walk(node.items, here, code ? [...groups, { code, at: here.length }] : groups);
  };
  walk(schema, [], []);
  if (dupes.length) throw new Error(`codes with two places in ${schema.title}:\n  ${dupes.join("\n  ")}`);
  const order = (c: string) => [c.startsWith("BG") ? 1 : 0, ...c.slice(3).split("-").map(Number)];
  return [...out.values()].sort((a, b) => {
    const x = order(a.code), y = order(b.code);
    for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? -1) !== (y[i] ?? -1)) return (x[i] ?? -1) - (y[i] ?? -1);
    return 0;
  });
}

/** The TypeScript type of one value at `pattern`, by indexed access into `root`. */
function typeAt(root: string, pattern: string): string {
  let t = root;
  for (const tok of pattern.split("/").slice(1)) t = tok === "~*" ? `NonNullable<${t}>[number]` : `NonNullable<${t}>[${JSON.stringify(tok)}]`;
  return `NonNullable<${t}>`;
}

function mapSource(name: string, entries: FieldEntry[]): string {
  const rows = entries.map((e) => {
    const extra = e.group ? `, group: ${JSON.stringify(e.group)}, rel: ${JSON.stringify(e.rel)}` : "";
    return `  ${JSON.stringify(e.code)}: { pattern: ${JSON.stringify(e.pattern)}, many: ${e.many}${extra} },`;
  });
  return `export const ${name} = {\n${rows.join("\n")}\n} as const;`;
}

function typesSource(name: string, root: string, entries: FieldEntry[]): string {
  const rows = entries.map((e) => `  ${JSON.stringify(e.code)}: ${typeAt(root, e.pattern)};`);
  return `export interface ${name} {\n${rows.join("\n")}\n}`;
}

/** The `generated/fields.ts` source. */
export function fieldsModule(schema: Schema): string {
  const read = fieldEntries(variantSchema(schema, "document"));
  const write = fieldEntries(variantSchema(schema, "input"));
  return `${BANNER}
// Each code's place in an invoice, and the type of its value. READ_FIELDS is
// over the document (\`Invoice\`), WRITE_FIELDS over the input (\`InvoiceInput\`):
// a code computed into the document (BT-112) is readable only, and a code the
// caller supplies at the top level but the document states under \`totals\`
// (BT-113) has one place in each.

import type { Invoice, InvoiceInput } from "./invoice-types.js";

${mapSource("READ_FIELDS", read)}

${mapSource("WRITE_FIELDS", write)}

/** The value of each code in a document. A list's code: one entry. */
${typesSource("FieldTypes", "Invoice", read)}

/** The value of each code in an input. */
${typesSource("InputFieldTypes", "InvoiceInput", write)}
`;
}

export async function buildArtifacts(): Promise<{ schemaTs: string; typesTs: string; fieldsTs: string }> {
  const schema = readSchema();
  return { schemaTs: schemaModule(schema), typesTs: await typesModule(schema), fieldsTs: fieldsModule(schema) };
}

async function main(): Promise<void> {
  const { schemaTs, typesTs, fieldsTs } = await buildArtifacts();
  writeFileSync(join(GEN_DIR, "schema.ts"), schemaTs);
  writeFileSync(join(GEN_DIR, "invoice-types.ts"), typesTs);
  writeFileSync(join(GEN_DIR, "fields.ts"), fieldsTs);
  process.stdout.write("Generated generated/schema.ts, invoice-types.ts, fields.ts\n");
}

// Run only when invoked directly (so importing this module from the artifacts
// test does not rewrite the committed files).
const invokedDirectly =
  argv[1] !== undefined && realpathSync(argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) await main();
